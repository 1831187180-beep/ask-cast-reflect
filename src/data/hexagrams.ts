// Helper: construct full Hexagram object with binary line array
function buildHexagram(raw: RawHexagramData): Hexagram {
  const lowerBinary = TRIGRAMS[raw.lowerTrigram].binary;
  const upperBinary = TRIGRAMS[raw.upperTrigram].binary;

  const lines: [BinaryDigit, BinaryDigit, BinaryDigit, BinaryDigit, BinaryDigit, BinaryDigit] = [
    lowerBinary[0],
    lowerBinary[1],
    lowerBinary[2],
    upperBinary[0],
    upperBinary[1],
    upperBinary[2],
  ];

  return {
    ...raw,
    lines,
  };
}

export const HEXAGRAMS: Hexagram[] = RAW_HEXAGRAMS.map(buildHexagram);

// Map by "UpperTrigram-LowerTrigram"
export const HEXAGRAM_MAP_BY_TRIGRAMS: Record<string, Hexagram> = {};
// Map by ID
export const HEXAGRAM_MAP_BY_ID: Record<number, Hexagram> = {};
// Map by binary line string e.g. "1,0,1,0,1,0"
export const HEXAGRAM_MAP_BY_BINARY: Record<string, Hexagram> = {};

HEXAGRAMS.forEach((hex) => {
  HEXAGRAM_MAP_BY_ID[hex.id] = hex;
  const key = `${hex.upperTrigram}-${hex.lowerTrigram}`;
  HEXAGRAM_MAP_BY_TRIGRAMS[key] = hex;
  HEXAGRAM_MAP_BY_BINARY[hex.lines.join(',')] = hex;
});
